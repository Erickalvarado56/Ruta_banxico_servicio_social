public class SentenciaIf {
    public static void main(String[] args) {
        System.out.println("Uso de sentencia IF");
        // uso de la sentencia if
        var edad = 5;

        if (edad >= 18){
            System.out.println("Eres mayor de edad");
        }
        else {
            System.out.println("Eres menor de edad");
        }
    }
}
